-- Служебные сообщения: пока только запись о звонке.
--
-- Звонок, не оставляющий следа, порождает вопрос «он мне звонил или нет?».
-- Запись кладётся в ту же ленту, что и сообщения, — там её и ищут.
--
-- Отдельной таблицей это делать не стоит: запись обязана встать в ленту на
-- своё место по времени, а сведение двух источников в одну ленту с общей
-- нумерацией и синхронизацией после обрыва — лишняя система на ровном месте.
ALTER TABLE messages ADD COLUMN kind text NOT NULL DEFAULT 'text';

-- Подробности служебного сообщения: длительность звонка, исход, кто звонил.
-- jsonb, а не колонки: у следующего вида служебных сообщений поля будут
-- свои, и заводить под каждое по колонке значит растить таблицу вширь ради
-- строк, которых в ней единицы процентов.
ALTER TABLE messages ADD COLUMN payload jsonb;
