-- Имя автора оригинала — снимком, а не ссылкой.
--
-- Получатель пересланного может быть незнаком с тем, кто написал оригинал:
-- его профиля у клиента нет, и подпись выходит «Переслано от …». Разрешать
-- имя запросом на каждое сообщение — лишний обход базы там, где оно уже
-- известно в момент пересылки.
--
-- Снимок ещё и честнее ссылки: человек переслал то, что было подписано так,
-- и позднее переименование чужого профиля не должно менять чужую переписку.
ALTER TABLE messages ADD COLUMN forwarded_name text;
