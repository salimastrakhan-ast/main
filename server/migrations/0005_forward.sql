-- Пересланное сообщение помнит, чьё оно было.
--
-- Без этого пересылка неотличима от «написал сам», и в переписке появляется
-- чужой текст от вашего имени — ровно то, чего в мессенджере быть не должно.
--
-- SET NULL при удалении пользователя: сообщение остаётся, подпись «переслано
-- от» исчезает вместе с аккаунтом. Удалять чужую переписку из-за того, что
-- кто-то ушёл, было бы хуже.
ALTER TABLE messages
    ADD COLUMN forwarded_from uuid REFERENCES users(id) ON DELETE SET NULL;
